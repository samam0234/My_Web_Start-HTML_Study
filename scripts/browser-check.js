import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:net';
import { chromium } from 'playwright';
import { createRepository } from '../server/repository.js';
import { createApp } from '../server/app.js';

// 실제 DOM → fetch → SQLite → DOM까지 확인하는 별도 브라우저 검사다.
const probe = createServer();
await new Promise(resolve => probe.listen(0, '127.0.0.1', resolve));
const port = probe.address().port;
await new Promise(resolve => probe.close(resolve));
const base = `http://127.0.0.1:${port}`;
const directory = await mkdtemp(join(tmpdir(), 'study-browser-'));
const config = { SQLITE_PATH: join(directory, 'browser.sqlite'), PUBLIC_ORIGIN: base, LOG_REQUESTS: 'false' };
const app = createApp(await createRepository(config), config);
await new Promise(resolve => app.server.listen(port, '127.0.0.1', resolve));
const browser = await chromium.launch();
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/workbook/`);
  await page.getByLabel('이메일', { exact: true }).fill('browser@example.com');
  await page.getByLabel('비밀번호 (12~128자)').fill('browser-password-123');
  await page.getByLabel('별명 (회원가입 시)').fill('브라우저 학습자');
  await page.getByRole('button', { name: '회원가입', exact: true }).click();
  await page.getByText('가입했습니다. 로그인하세요.', { exact: true }).waitFor();
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await page.getByText('브라우저 학습자님 로그인 중', { exact: true }).waitFor();
  await page.getByLabel('제목', { exact: true }).fill('<img src=x onerror=alert(1)> HTML');
  await page.getByLabel('내용', { exact: true }).fill('HTML은 구조이고 CSS는 표현입니다.');
  await page.getByLabel('태그 (쉼표로 구분)').fill('html, css');
  await page.getByRole('button', { name: '저장', exact: true }).click();
  await page.getByText('작성했습니다.', { exact: true }).waitFor();
  assert.equal(await page.locator('#post-detail img').count(), 0);
  await page.getByLabel('댓글', { exact: true }).fill('브라우저 댓글');
  await page.getByRole('button', { name: '댓글 작성', exact: true }).click();
  await page.locator('#comments li').filter({ hasText: '브라우저 학습자: 브라우저 댓글' }).waitFor();
  await page.getByRole('button', { name: '수정', exact: true }).click();
  await page.getByLabel('제목', { exact: true }).fill('수정한 HTML');
  await page.getByRole('button', { name: '저장', exact: true }).click();
  await page.getByText('수정했습니다.', { exact: true }).waitFor();
  await page.getByRole('button', { name: '다크모드', exact: true }).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  await page.getByRole('link', { name: '문서 AI', exact: true }).click();
  await page.getByLabel('문서', { exact: true }).setInputFiles({ name: 'study.md', mimeType: 'text/markdown', buffer: Buffer.from('HTML은 구조이고 CSS는 표현입니다.') });
  await page.getByRole('button', { name: '업로드', exact: true }).click();
  await page.getByText('문서를 저장했습니다.', { exact: true }).waitFor();
  await page.getByLabel('질문', { exact: true }).fill('HTML');
  await page.getByRole('button', { name: '스트리밍 질문', exact: true }).click();
  await page.getByText('응답이 완료되었습니다.', { exact: true }).waitFor();
  assert.match(await page.locator('#answer').innerText(), /모의 응답/);
  await page.getByRole('button', { name: '질문 기록', exact: true }).click();
  await page.locator('#history-list li').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/workbook-mobile.png', fullPage: true });
  await page.getByRole('link', { name: '게시글', exact: true }).click();
  await page.getByRole('link', { name: '수정한 HTML', exact: true }).click();
  await page.getByRole('button', { name: '삭제', exact: true }).click();
  await page.getByText('삭제했습니다.', { exact: true }).waitFor();
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  assert.match(await page.locator('#identity').innerText(), /로그인 전/);
  await page.goto(`${base}/final-project/`);
  await page.evaluate(() => localStorage.setItem('final-project-todos', '{}'));
  await page.reload();
  await page.getByLabel('할 일', { exact: true }).fill('저장되는 Todo');
  await page.locator('#todo-form button').click();
  await page.getByText('저장되는 Todo', { exact: true }).waitFor();
  await page.reload();
  await page.getByText('저장되는 Todo', { exact: true }).waitFor();
  await page.goto(`${base}/lessons/study1/`);
  await page.getByLabel('이름', { exact: true }).fill('하나');
  await page.getByRole('button', { name: '인사', exact: true }).click();
  assert.match(await page.locator('#greeting').innerText(), /하나/);
  await page.goto(`${base}/lessons/study12/`);
  await page.getByLabel('제목 (1~200자)').fill('라이브러리 연결');
  await page.getByRole('button', { name: '서버 검사', exact: true }).click();
  await page.getByText('입력 검사를 통과했습니다.', { exact: true }).waitFor();
  assert.match(await page.locator('#demo-count').innerText(), /1회/);
  assert.deepEqual(errors, []);
  const result = { browser: 'Chromium', desktop: '1280x900', mobile: '390x844', flow: ['회원가입', '로그인', '게시글 CRUD', '댓글', 'XSS 텍스트 출력', 'Worker 업로드', 'SSE 모의 AI', '질문 기록', '테마 저장', 'Todo 손상값 복구'], pageErrors: errors };
  await writeFile('artifacts/browser-result.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); await app.close(); await rm(directory, { recursive: true, force: true }); }
